namespace BindingGenerator;

using System;
using System.IO;
using System.Linq;
using System.Text;
using CppAst;

internal static class Program
{
    private static int Main(string[] args)
    {
        string headerPath = args.Length > 0 ? args[0] : "external/meshoptimizer/src/meshoptimizer.h";
        string outputPath = args.Length > 1 ? args[1] : "MeshOptimizer/Native/MeshOptimizer.Bindings.cs";

        // Strip standard C header includes and prepend built-in size_t typedef so parsing works
        // reliably across Windows, Linux, and macOS without requiring system header paths.
        var headerLines = File.ReadAllLines(headerPath)
            .Where(line =>
            {
                string trimmed = line.Trim();
                return trimmed != "#include <assert.h>" && trimmed != "#include <stddef.h>";
            });
        string headerText = "typedef __SIZE_TYPE__ size_t;\n" + string.Join('\n', headerLines);

        var options = new CppParserOptions
        {
            ParserKind = CppParserKind.C,
            AutoSquashTypedef = false,
            ParseComments = true,
        };

        var compilation = CppParser.Parse(headerText, options);

        if (compilation.HasErrors)
        {
            foreach (var diag in compilation.Diagnostics.Messages)
                Console.Error.WriteLine(diag);
            return 1;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace MeshOptimizer;");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.IO;");
        sb.AppendLine("using System.Reflection;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Runtime.InteropServices;");
        sb.AppendLine();

        foreach (var cppEnum in compilation.Enums)
        {
            if (cppEnum.Items.Count == 0 || !cppEnum.Items.All(i => i.Name.StartsWith("meshopt_")))
                continue;

            bool isAnonymous = string.IsNullOrEmpty(cppEnum.Name) || !cppEnum.Name.StartsWith("meshopt_");
            string enumName = !isAnonymous
                ? ToPascalCase(cppEnum.Name["meshopt_".Length..])
                : $"{ExtractGroupPrefix(cppEnum.Items[0].Name["meshopt_".Length..])}Options";

            AppendComment(sb, cppEnum.Comment, "");
            if (isAnonymous)
            {
                sb.AppendLine("[Flags]");
                sb.AppendLine($"public enum {enumName} : uint");
            }
            else
            {
                sb.AppendLine($"public enum {enumName}");
            }
            sb.AppendLine("{");
            foreach (var item in cppEnum.Items)
            {
                AppendComment(sb, item.Comment, "    ");
                string itemName = item.Name.StartsWith("meshopt_")
                    ? ToPascalCase(item.Name["meshopt_".Length..])
                    : item.Name;
                string suffix = isAnonymous ? "u" : "";
                sb.AppendLine($"    {itemName} = {item.Value}{suffix},");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        foreach (var cppStruct in compilation.Classes)
        {
            if (!cppStruct.Name.StartsWith("meshopt_") || cppStruct.Fields.Count == 0)
                continue;

            string structName = ToPascalCase(cppStruct.Name["meshopt_".Length..]);
            AppendComment(sb, cppStruct.Comment, "");
            sb.AppendLine("[StructLayout(LayoutKind.Sequential)]");
            sb.AppendLine($"public unsafe struct {structName}");
            sb.AppendLine("{");
            foreach (var field in cppStruct.Fields)
            {
                AppendComment(sb, field.Comment, "    ");
                if (field.Type is CppArrayType arrayType)
                {
                    sb.AppendLine($"    public fixed {MapType(arrayType.ElementType)} {EscapeIdentifier(field.Name)}[{arrayType.Size}];");
                }
                else
                {
                    sb.AppendLine($"    public {MapType(field.Type)} {EscapeIdentifier(field.Name)};");
                }
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.AppendLine("public static unsafe partial class MeshOpt");
        sb.AppendLine("{");
        sb.AppendLine("    private const string LibraryName = \"meshoptimizer\";");
        sb.AppendLine();
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void InitializeResolver()");
        sb.AppendLine("    {");
        sb.AppendLine("        NativeLibrary.SetDllImportResolver(typeof(MeshOpt).Assembly, ResolveNativeLibrary);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static IntPtr ResolveNativeLibrary(string libraryName, Assembly assembly, DllImportSearchPath? searchPath)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (libraryName != LibraryName)");
        sb.AppendLine("            return IntPtr.Zero;");
        sb.AppendLine();
        sb.AppendLine("        string? rid = null;");
        sb.AppendLine("        string? fileName = null;");
        sb.AppendLine();
        sb.AppendLine("        if (OperatingSystem.IsWindows())");
        sb.AppendLine("        {");
        sb.AppendLine("            rid = RuntimeInformation.ProcessArchitecture switch");
        sb.AppendLine("            {");
        sb.AppendLine("                Architecture.X64 => \"win-x64\",");
        sb.AppendLine("                Architecture.Arm64 => \"win-arm64\",");
        sb.AppendLine("                Architecture.X86 => \"win-x86\",");
        sb.AppendLine("                _ => null");
        sb.AppendLine("            };");
        sb.AppendLine("            fileName = \"meshoptimizer.dll\";");
        sb.AppendLine("        }");
        sb.AppendLine("        else if (OperatingSystem.IsLinux())");
        sb.AppendLine("        {");
        sb.AppendLine("            rid = RuntimeInformation.ProcessArchitecture switch");
        sb.AppendLine("            {");
        sb.AppendLine("                Architecture.X64 => \"linux-x64\",");
        sb.AppendLine("                Architecture.Arm64 => \"linux-arm64\",");
        sb.AppendLine("                _ => null");
        sb.AppendLine("            };");
        sb.AppendLine("            fileName = \"libmeshoptimizer.so\";");
        sb.AppendLine("        }");
        sb.AppendLine("        else if (OperatingSystem.IsMacOS())");
        sb.AppendLine("        {");
        sb.AppendLine("            rid = RuntimeInformation.ProcessArchitecture switch");
        sb.AppendLine("            {");
        sb.AppendLine("                Architecture.Arm64 => \"osx-arm64\",");
        sb.AppendLine("                Architecture.X64 => \"osx-x64\",");
        sb.AppendLine("                _ => \"osx\"");
        sb.AppendLine("            };");
        sb.AppendLine("            fileName = \"libmeshoptimizer.dylib\";");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        if (rid != null && fileName != null)");
        sb.AppendLine("        {");
        sb.AppendLine("            string baseDir = AppContext.BaseDirectory;");
        sb.AppendLine("            string candidate = Path.Combine(baseDir, \"runtimes\", rid, \"native\", fileName);");
        sb.AppendLine("            if (File.Exists(candidate) && NativeLibrary.TryLoad(candidate, out IntPtr handle))");
        sb.AppendLine("                return handle;");
        sb.AppendLine();
        sb.AppendLine("            if (OperatingSystem.IsMacOS())");
        sb.AppendLine("            {");
        sb.AppendLine("                string universalCandidate = Path.Combine(baseDir, \"runtimes\", \"osx\", \"native\", fileName);");
        sb.AppendLine("                if (File.Exists(universalCandidate) && NativeLibrary.TryLoad(universalCandidate, out handle))");
        sb.AppendLine("                    return handle;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        return IntPtr.Zero;");
        sb.AppendLine("    }");
        sb.AppendLine();

        foreach (var func in compilation.Functions)
        {
            if (!func.Name.StartsWith("meshopt_"))
                continue;

            string rawName = func.Name["meshopt_".Length..];
            string pascalName = ToPascalCase(rawName);
            string returnType = MapType(func.ReturnType);

            AppendComment(sb, func.Comment, "    ");
            sb.AppendLine($"    [LibraryImport(LibraryName, EntryPoint = \"{func.Name}\")]");
            sb.Append($"    public static partial {returnType} {pascalName}(");

            var parameters = func.Parameters.Select((p, idx) =>
            {
                string paramName = string.IsNullOrEmpty(p.Name) ? $"arg{idx}" : EscapeIdentifier(p.Name);
                return $"{MapType(p.Type)} {paramName}";
            });
            sb.Append(string.Join(", ", parameters));
            sb.AppendLine(");");
            sb.AppendLine();
        }

        sb.AppendLine("}");

        string? outputDir = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrEmpty(outputDir))
            Directory.CreateDirectory(outputDir);

        File.WriteAllText(outputPath, sb.ToString());
        Console.WriteLine($"Generated bindings written to {outputPath}");
        return 0;
    }

    private static string ExtractGroupPrefix(string name)
    {
        int underscoreIdx = name.IndexOf('_');
        if (underscoreIdx > 0)
            return ToPascalCase(name[..underscoreIdx]);

        for (int i = 1; i < name.Length; i++)
        {
            if (char.IsUpper(name[i]))
                return name[..i];
        }

        return name;
    }

    private static string ToPascalCase(string input)
    {
        if (string.IsNullOrEmpty(input)) return input;
        var parts = input.Split('_', StringSplitOptions.RemoveEmptyEntries);
        return string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
    }

    private static string MapType(CppType type)
    {
        switch (type)
        {
            case CppQualifiedType qualified:
                return MapType(qualified.ElementType);

            case CppTypedef typedefType:
                return typedefType.Name switch
                {
                    "size_t" => "nuint",
                    _ => MapType(typedefType.ElementType)
                };

            case CppPrimitiveType primitive:
                return primitive.Kind switch
                {
                    CppPrimitiveKind.Void => "void",
                    CppPrimitiveKind.Bool => "byte",
                    CppPrimitiveKind.Char => "sbyte",
                    CppPrimitiveKind.Short => "short",
                    CppPrimitiveKind.Int => "int",
                    CppPrimitiveKind.LongLong => "long",
                    CppPrimitiveKind.UnsignedChar => "byte",
                    CppPrimitiveKind.UnsignedShort => "ushort",
                    CppPrimitiveKind.UnsignedInt => "uint",
                    CppPrimitiveKind.UnsignedLongLong => "nuint",
                    CppPrimitiveKind.Float => "float",
                    CppPrimitiveKind.Double => "double",
                    _ => "void*"
                };

            case CppClass cppClass:
                return cppClass.Name.StartsWith("meshopt_")
                    ? ToPascalCase(cppClass.Name["meshopt_".Length..])
                    : cppClass.Name;

            case CppEnum cppEnum:
                return cppEnum.Name.StartsWith("meshopt_")
                    ? ToPascalCase(cppEnum.Name["meshopt_".Length..])
                    : "int";

            case CppPointerType ptr:
                var elem = ptr.ElementType;
                while (elem is CppQualifiedType q)
                    elem = q.ElementType;

                if (elem is CppFunctionType fnType)
                {
                    var fnArgs = fnType.Parameters.Select(p => MapType(p.Type)).Append(MapType(fnType.ReturnType));
                    return $"delegate* unmanaged[Cdecl]<{string.Join(", ", fnArgs)}>";
                }

                return $"{MapType(ptr.ElementType)}*";

            default:
                return "void*";
        }
    }

    private static string EscapeIdentifier(string name) => name switch
    {
        "out" or "in" or "ref" or "object" or "string" or "fixed" or "params" or "base" => $"@{name}",
        _ => name
    };

    private static void AppendComment(StringBuilder sb, CppComment? comment, string indent)
    {
        if (comment == null) return;
        var lines = comment.ToString().Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.RemoveEmptyEntries);
        sb.AppendLine($"{indent}/// <summary>");
        foreach (var line in lines)
        {
            string cleaned = line.Trim().TrimStart('/', '*', ' ');
            if (!string.IsNullOrWhiteSpace(cleaned))
                sb.AppendLine($"{indent}/// {System.Security.SecurityElement.Escape(cleaned)}");
        }
        sb.AppendLine($"{indent}/// </summary>");
    }
}
